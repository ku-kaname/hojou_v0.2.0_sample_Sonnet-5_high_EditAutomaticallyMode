"""
日次バッチ共通処理

【概要】
返却期限通知・ノーショー自動取消等の日次バッチジョブを定期実行するスケジューラを提供する
"""

from apscheduler.schedulers.background import BackgroundScheduler

scheduler = BackgroundScheduler(timezone="Asia/Tokyo")

# ====================================================================================================
# スケジューラ起動・停止
# - start_scheduler : スケジューラ起動
# - shutdown_scheduler : スケジューラ停止

# 設計書：設計書/アーキテクチャ方針_v0.2.0.md
# ====================================================================================================


def start_scheduler() -> None:
    """
    スケジューラ起動

    設計書：設計書/アーキテクチャ方針_v0.2.0.md

    【処理概要】
    - 日次バッチジョブのスケジューラを起動する
    - 個々のジョブ登録は、対応する機能群の実装バックログで本処理に追記する（本タスクの時点ではジョブ未登録）

    【パラメータ】
    - なし

    【戻り値】
    - なし

    【例外処理】
    - なし

    【処理フロー】
    1. スケジューラの起動
    """

    # 1. スケジューラの起動
    scheduler.start()


def shutdown_scheduler() -> None:
    """
    スケジューラ停止

    設計書：設計書/アーキテクチャ方針_v0.2.0.md

    【処理概要】
    - 日次バッチジョブのスケジューラを停止する

    【パラメータ】
    - なし

    【戻り値】
    - なし

    【例外処理】
    - なし

    【処理フロー】
    1. スケジューラの停止
    """

    # 1. スケジューラの停止
    scheduler.shutdown()
